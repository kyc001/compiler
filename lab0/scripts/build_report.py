#!/usr/bin/env python3
"""Build the existing report with Tectonic, including Windows Tectonic from WSL."""

from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
LAB0 = ROOT / "lab0"


def main():
    configured = os.environ.get("TECTONIC")
    tool = configured or shutil.which("tectonic") or shutil.which("tectonic.exe")
    if not tool:
        raise RuntimeError("Tectonic is required. Add it to PATH or set TECTONIC to its executable.")
    build = LAB0 / "build/report"
    output = LAB0 / "output/pdf/preparation.pdf"
    build.mkdir(parents=True, exist_ok=True)
    output.parent.mkdir(parents=True, exist_ok=True)

    def argument_path(path):
        if os.name != "nt" and tool.lower().endswith((".exe", ".cmd")):
            return subprocess.check_output(["wslpath", "-w", str(path)], text=True).strip()
        return str(path)

    environment = os.environ.copy()
    search_options = []
    noto = Path("/usr/share/fonts/opentype/noto")
    if noto.is_dir():
        search_options = ["-Z", "search-path=" + argument_path(noto)]
    if os.name != "nt" and tool.lower().endswith(".exe") and "FONTCONFIG_FILE" not in environment:
        # Windows Tectonic cannot discover WSL's Noto fonts via its default config.
        # Keep this machine-specific config and cache inside the cleanable build tree.
        font_dirs = [Path("/usr/share/fonts/opentype/noto"),
                     Path("/usr/share/fonts/truetype/dejavu")]
        dirs = [f"<dir>{escape(argument_path(path).replace(chr(92), '/'))}</dir>"
                for path in font_dirs if path.is_dir()]
        if dirs:
            cache = build / "font-cache"
            cache.mkdir(exist_ok=True)
            config = build / "fontconfig.xml"
            config.write_text('<?xml version="1.0"?><fontconfig>' + "".join(dirs)
                              + "<cachedir>" + escape(argument_path(cache).replace(chr(92), "/"))
                              + "</cachedir></fontconfig>", encoding="utf-8")
            environment["FONTCONFIG_FILE"] = argument_path(config)
            environment["WSLENV"] = ":".join(filter(None, [
                environment.get("WSLENV", ""), "FONTCONFIG_FILE"]))

    subprocess.run([tool, *search_options, "--keep-logs", "--keep-intermediates",
                    "--outdir", argument_path(build),
                    argument_path(LAB0 / "report/preparation.tex")],
                   cwd=ROOT, env=environment, check=True)
    pdf = build / "preparation.pdf"
    if not pdf.is_file() or pdf.stat().st_size == 0:
        raise RuntimeError("Tectonic did not produce a nonempty PDF.")
    log = (build / "preparation.log").read_text(encoding="utf-8", errors="replace")
    errors = ("Missing character:", "Overfull \\hbox", "Overfull \\vbox",
              "There were undefined references", "There were undefined citations")
    if any(marker in log for marker in errors):
        raise RuntimeError("PDF has missing glyphs, overflowing content or unresolved references; "
                           "inspect lab0/build/report/preparation.log before exporting.")
    shutil.copyfile(pdf, output)
    page_count = None
    if shutil.which("pdfinfo"):
        info = subprocess.check_output(["pdfinfo", str(output)], text=True)
        match = re.search(r"(?m)^Pages:\s+(\d+)", info)
        page_count = int(match.group(1)) if match else None
    evidence = LAB0 / "report/evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    record = {
        "compiler": subprocess.check_output([tool, "--version"], text=True).strip(),
        "source": "lab0/report/preparation.tex",
        "output": "lab0/output/pdf/preparation.pdf",
        "template": "materials/templates/LaTeX模板.zip",
        "page_count": page_count,
        "compiled_at": datetime.now(timezone.utc).isoformat(),
        "source_sha256": hashlib.sha256((LAB0 / "report/preparation.tex").read_bytes()).hexdigest(),
        "pdf_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "checks": {"missing_glyphs": False, "overflow": False, "unresolved_references": False},
        "underfull_hbox_warnings": log.count("Underfull \\hbox"),
        "notes": "Generated by make report. Visual review is recorded separately in lab0/report/review.md."
    }
    (evidence / "report-build.json").write_text(
        json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Report: {output}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"Report build failed: {error}", file=sys.stderr)
        sys.exit(1)
